/** Реплика героя о кафе игрока сейчас */
export function heroLine(hero: HeroId, status: RegularStatus, reason?: RejectReason): string {
  const l = LINES[hero];
  if (status !== 'lost') return l[status];
  return (reason && l.lost[reason]) || l.lost.other;
}

/** Короткие слова — к следующему неразрывным пробелом, тире — к предыдущему: тексты героев длинные, переносятся */
const SHORT = /(?<=^|[\s(«])(а|и|в|во|на|с|со|к|ко|о|об|у|не|ни|но|по|за|до|от|из|для|без|что|как|я|ты|мы|вы|он|же|ли|бы|ну|уж|мне|вас|вам|нас|там|тут|раз) (?=\S)/gi;
export function bindShort(text: string): string {
  let out = text.replace(/ —/g, '\u00a0—');
  // Просмотр назад не съедает пробел перед словом — короткие слова подряд («а у меня») связываются за один проход
  out = out.replace(SHORT, (_m, w: string) => `${w}\u00a0`);
  return out;
}
