/** Из чего сделана позиция — для подписи в меню. Пустой список — состава нет. */
export function compositionOf(itemId: string): string[] {
  const dish = parseDish(itemId);
  if (dish) return [...BASE_COMPOSITION[dish.base.id], ...dish.addIns.map((a) => a.name.toLowerCase())];
  return COMPOSITION[itemId] ?? [];
}
